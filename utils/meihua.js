/* ============ 卦象运算 ============ */
function hexBinary(up,down){ // 返回 6 位，0=初(底) ... 5=上(顶)
  const u=TRIGRAM[up].bits, d=TRIGRAM[down].bits;
  return [d[0],d[1],d[2], u[0],u[1],u[2]];
}
function upDownFromBits(bits){ // bits[0..2]=下, bits[3..5]=上
  return {down:numOfBits([bits[0],bits[1],bits[2]]), up:numOfBits([bits[3],bits[4],bits[5]])};
}
function huGua(bits){ // 互卦：下互=二三四，上互=三四五
  const down=numOfBits([bits[1],bits[2],bits[3]]);
  const up=numOfBits([bits[2],bits[3],bits[4]]);
  return {down,up};
}
function bianGua(bits,dong){ // dong 1-6，动爻阴阳反转
  const b=bits.slice();
  b[dong-1]=b[dong-1]?0:1;
  return b;
}

/* ============ 起卦（DOM 无关，返回结构化结果） ============ */
function rnd(n){return Math.floor(Math.random()*n)+1;}
function castMeihua(input){
  input = input || {};
  let up,down,dong;
  if(input.mode==='num'){
    const a=parseInt(input.n1,10)||rnd(8);
    const b=parseInt(input.n2,10)||rnd(8);
    up=((a%8)||8); down=((b%8)||8); dong=(((a+b)%6)||6);
  } else if(input.mode==='time'){
    const t=new Date();
    const sum=t.getFullYear()+(t.getMonth()+1)+t.getDate()+t.getHours();
    const s2=t.getFullYear()+(t.getMonth()+1)+t.getDate();
    up=((s2%8)||8); down=((sum%8)||8); dong=((sum%6)||6);
  } else {
    up=rnd(8); down=rnd(8); dong=rnd(6);
  }
  const ben=hexBinary(up,down);
  const hu=huGua(ben);
  const bianB=bianGua(ben,dong);
  const bianUD=upDownFromBits(bianB);
  const benKey=up+'-'+down, huKey=hu.up+'-'+hu.down, bianKey=bianUD.up+'-'+bianUD.down;
  const tiEl=TRIGRAM[down].el, yongEl=TRIGRAM[up].el;
  const v=tiYongVerdict(tiEl,yongEl);
  const dongInTi = dong<=3;
  return {
    up,down,dong,
    benKey,huKey,bianKey,
    ben:{key:benKey, meta:HEX[benKey], bai:BAI[benKey], bits:ben, dong},
    hu:{key:huKey, meta:HEX[huKey], bai:BAI[huKey], bits:hexBinary(hu.up,hu.down), dong:0},
    bian:{key:bianKey, meta:HEX[bianKey], bai:BAI[bianKey], bits:bianB, dong:0},
    tiEl, yongEl, verdict:v, dongInTi
  };
}

