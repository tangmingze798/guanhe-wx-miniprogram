/* 把吉凶档（梅花 吉/小吉/平/凶；六壬 吉/凶/半）归一为 g·m·b */
function toneBucket(lv){ if(lv==='吉'||lv==='小吉') return 'g'; if(lv==='半'||lv==='平') return 'm'; return 'b'; }

/* 识别所问类别 */
function classify(q){
  if(!q) return null;
  const s=String(q).toLowerCase();
  for(const c of CATEGORY){ for(const k of c.kws){ if(s.indexOf(k.toLowerCase())>=0) return c; } }
  return null;
}

